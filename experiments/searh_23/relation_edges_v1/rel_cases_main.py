"""Case definitions for the relation-edges research (RELATION_GRAPH_v1).

Research question: given already-found source-backed events, build the correct
typed edges between them (PAIR RETRIEVER -> RELATION DETECTOR -> RELATION
CLASSIFIER -> GROUP LOGIC), instead of asking one LLM for the full graph.

Dataset design (frozen BEFORE any inference):
  - 22 main cases + 8 mini cases (post-hoc validation only), fresh domains
    (no banking/retail/hotel/service-desk and no reuse of the 20+10 domains of
    operation_check_v1).
  - Controlled graph shapes (see REQUIRED_CONSTRUCTIONS in rel_freeze.py).
  - Minimal pairs: MP1 binding target, MP2 direction, MP3 AND vs OR,
    MP4 condition vs same-phrase descriptive, MP5 renamed suite, MP6 same
    events / different clause structure.
  - Tool catalogs carry description + schema; names are semantics-free for the
    name-blind arms; two misleading names with correct descriptions included.

Gold conventions (fixed before inference):
  - Event role = nature of the event (OPERATION_EFFECT / PRECONDITION_CHECK /
    STATE_OBSERVATION / COMMUNICATION / OTHER-descriptive).
  - Edge direction: from the earlier/gating/triggering event to the
    later/gated/obligated operation. ORDER_AFTER never appears in gold; the
    scorer maps a reversed ordered pair to ORDER_AFTER.
  - relation types: PRECONDITION (antecedent is an executable check),
    STATE_GATE (antecedent is a state that must hold), ORDER_BEFORE (op must
    precede op), RESPONSE (antecedent completion triggers obligation, esp.
    communication/archival), EXCEPTION ("unless" negative gate), EVEN_IF
    (explicitly non-blocking).
  - acceptable: verdict-plausible alternative types for single-answer scoring;
    a classifier answer in `acceptable` counts as correct.
  - groups: AND/OR condition logic over the set of parents bound to one
    operation (PET-style gateway typing).
"""
