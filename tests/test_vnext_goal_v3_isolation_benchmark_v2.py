"""Corpus structure and authored-gold consistency, entirely offline."""

from collections import Counter
import runpy
from pathlib import Path

from guardian_truth.vnext.goal_v3_user_contract_v2 import parse_user_contract_v2
from guardian_truth.vnext.goal_v3_user_execution_v2 import evaluate_user_source_v2
from guardian_truth.vnext.goal_v3_user_certificates_v2 import issue_user_certificate_v2
from guardian_truth.vnext.integrity import digest


ROOT = Path(__file__).resolve().parents[1]
CORPUS = runpy.run_path(str(ROOT / "benchmarks/vnext/goal_v3_isolation_cases_v2.py"))


def test_exact_inventory_stages_families_and_source_gold_separation():
    cases = CORPUS["build_cases"]()
    assert len(cases) == len({row["case_id"] for row in cases}) == 60
    assert Counter(row["split"] for row in cases) == {"CORE": 48, "STRESS": 12}
    assert Counter(row["pair_id"] for row in cases if row["pair_id"]) == {
        f"V2P{index:02d}": 2 for index in range(1, 25)}
    assert {family for row in cases for family in row["families"]} == {f"F{i}" for i in range(1, 17)}
    s1 = CORPUS["S1_CASE_IDS"]
    assert len(s1) == len(set(s1)) == len({cid.split(":")[0] for cid in s1}) == 12
    assert set(s1) <= {row["case_id"] for row in cases if row["split"] == "CORE"}
    for row in cases:
        assert not any(key in row["source"] for key in ("policy", "gold", "reference"))
        assert row["gold"]["expected_entity"] == "LIC-739"
        assert row["gold"]["expected_actor"] == "assistant"
        assert row["gold"]["expected_status"] in {
            "PROVED_ERROR", "PROVED_NO_ERROR", "UNRESOLVED", "INCONSISTENT"}


def test_each_pair_changes_only_its_declared_factor():
    core = [row for row in CORPUS["build_cases"]() if row["split"] == "CORE"]
    for first, second in zip(core[::2], core[1::2]):
        assert first["pair_id"] == second["pair_id"]
        replacement = second["source"]
        for part in first["factor_path"]:
            replacement = replacement[part]
        assert CORPUS["changed"](first["source"], first["factor_path"], replacement) == second["source"]
        assert first["source"] != second["source"]
        if first["invariant"]:
            assert first["gold"]["expected_status"] == second["gold"]["expected_status"]
            assert first["gold"]["expected_alignment"] == second["gold"]["expected_alignment"]


def test_fresh_cases_not_reused_v1_or_unit_fixture_and_build_is_stable():
    cases = CORPUS["build_cases"]()
    old = runpy.run_path(str(ROOT / "benchmarks/vnext/goal_v3_isolation_cases_v1.py"))["cases"]()
    assert not {digest(row["source"]) for row in cases} & {digest(row["input"]) for row in old}
    assert all("ORDER-82" not in row["source"]["user_messages"][0]["text"] for row in cases)
    cases[0]["source"]["tool_catalog"]["license_read"]["version"] = "tampered"
    assert CORPUS["build_cases"]()[0]["source"]["tool_catalog"]["license_read"]["version"] == "7"
    assert CORPUS["build_cases"]() == CORPUS["build_cases"]()


def test_out_of_fragment_definitive_gold_is_not_relabelled_unknown():
    cases = CORPUS["build_cases"]()
    unsupported = [row for row in cases if parse_user_contract_v2(row["source"]) is None]
    assert len(unsupported) == 7
    assert sum(row["gold"]["expected_status"] in {"PROVED_ERROR", "PROVED_NO_ERROR"}
        for row in unsupported) == 4
    assert all(evaluate_user_source_v2(row["source"]) is None for row in unsupported)


def test_supported_fragment_status_and_replay_against_authored_gold():
    # This is a source-compiler unit audit, NOT the future LLM experiment metric.
    # Gold is authored in the corpus and is not generated by either evaluator.
    status_map = {"ERROR_CANDIDATE": "PROVED_ERROR", "NO_ERROR_CANDIDATE": "PROVED_NO_ERROR",
        "UNRESOLVED": "UNRESOLVED", "INCONSISTENT": "INCONSISTENT"}
    for row in CORPUS["build_cases"]():
        evaluated = evaluate_user_source_v2(row["source"])
        if evaluated is None:
            continue
        contract, candidate, primitives = evaluated
        expected = row["gold"]
        assert status_map[candidate.status.value] == expected["expected_status"], row["case_id"]
        assert candidate.alignment.value == expected["expected_alignment"], row["case_id"]
        effects = {fact.rule_id.split(":")[-1]: fact.value.value for fact in primitives
            if fact.query == "CONFIRMED_EFFECT"}
        assert effects == expected["expected_effect_status"], row["case_id"]
        world = candidate.worlds[0]
        outcomes, temporal = {}, {}
        for clause in contract.clauses:
            key = clause.rule_id.split(":")[-1]
            if key not in expected["expected_rule_outcomes"]:
                continue
            temporal[key] = ("DEADLINE_PASSED" if row["source"]["session_complete"] else "NOT_DUE_YET") \
                if clause.kind == "REQUIRE_EFFECT_BY_SESSION" else "BEFORE_TARGET"
            if clause.rule_id in world.violated_rule_ids:
                outcome = "VIOLATED"
            elif clause.rule_id in world.inconsistent_rule_ids:
                outcome = "BOTH"
            elif clause.rule_id in world.unresolved_rule_ids:
                outcome = "UNKNOWN"
            elif clause.rule_id in world.pending_rule_ids:
                outcome = "NOT_DUE_YET"
            else:
                inactive = clause.trigger_tool is not None and (
                    clause.trigger_tool != row["source"]["target_action"]["tool"]
                    or contract.entity != row["source"]["target_action"]["entity"])
                guard_false = any(fact.rule_id == clause.rule_id and fact.tool == clause.guard_tool
                    and fact.value.value == "FALSE" for fact in primitives)
                outcome = "NOT_APPLICABLE" if inactive or guard_false else "SATISFIED"
            outcomes[key] = outcome
        assert outcomes == expected["expected_rule_outcomes"], row["case_id"]
        assert temporal == expected["expected_temporal_status"], row["case_id"]
        certificate = issue_user_certificate_v2(row["source"], candidate)
        assert (certificate is not None) == (expected["expected_status"] in
            {"PROVED_ERROR", "PROVED_NO_ERROR"}), row["case_id"]
